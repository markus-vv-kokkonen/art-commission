/**
 * Wire — emit the asset manifest the game consumes.
 *
 * Scans the output tree for files that exist, then writes ONE JSON manifest
 * mapping channel → key → path (paths relative to assetRoot, forward
 * slashes). The intended game-side pattern is a guarded lookup per channel:
 * key present → load the procured file, key absent → code-drawn fallback.
 * That keeps every generated asset strictly additive.
 *
 * Only enabled assets wire — flipping an asset to enabled:false unwires it on
 * the next run even if its PNG still exists (descoping a class is one flag).
 *
 * `--ts` additionally emits a TypeScript module (same path, .ts) with one
 * exported const per channel, for engines that prefer a typed import.
 */

import { existsSync } from 'node:fs';
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import type { ResolvedCommission } from './types.js';

export interface ManifestAssetEntry {
  out: string;
  channel: string;
  key: string;
  kind?: string;
  group?: string;
  px?: [number, number];
}

export interface ArtManifest {
  $generator: 'art-commission';
  version: 1;
  name: string;
  counts: { catalogued: number; wired: number };
  /** channel → key → out path (relative to assetRoot). */
  channels: Record<string, Record<string, string>>;
  /** every wired id, with its metadata. */
  assets: Record<string, ManifestAssetEntry>;
}

const fwd = (p: string): string => p.replace(/\\/g, '/');

export interface WireScan {
  manifest: ArtManifest;
  /** enabled ids (assets + derives) with no file on disk. */
  missing: string[];
  catalogued: number;
}

export function buildManifest(c: ResolvedCommission): WireScan {
  const channels: Record<string, Record<string, string>> = {};
  const assets: Record<string, ManifestAssetEntry> = {};
  const missing: string[] = [];
  let catalogued = 0;

  const add = (id: string, entry: ManifestAssetEntry, present: boolean) => {
    catalogued++;
    if (!present) { missing.push(id); return; }
    (channels[entry.channel] ??= {})[entry.key] = fwd(entry.out);
    assets[id] = { ...entry, out: fwd(entry.out) };
  };

  for (const a of c.assets) {
    if (!a.enabled) continue;
    add(a.id, { out: a.out, channel: a.channel, key: a.key, kind: a.kind, group: a.group, px: a.px }, existsSync(a.outAbs));
    for (const d of a.derive) {
      add(d.id, { out: d.out, channel: d.channel, key: d.key, kind: a.kind, group: a.group, px: d.px }, existsSync(d.outAbs));
    }
  }

  // deterministic output: sort channels and keys so reruns diff cleanly
  const sortedChannels: Record<string, Record<string, string>> = {};
  for (const ch of Object.keys(channels).sort()) {
    sortedChannels[ch] = Object.fromEntries(Object.entries(channels[ch]).sort(([a], [b]) => a.localeCompare(b)));
  }
  const sortedAssets = Object.fromEntries(Object.entries(assets).sort(([a], [b]) => a.localeCompare(b)));

  return {
    manifest: {
      $generator: 'art-commission',
      version: 1,
      name: c.name,
      counts: { catalogued, wired: Object.keys(sortedAssets).length },
      channels: sortedChannels,
      assets: sortedAssets,
    },
    missing,
    catalogued,
  };
}

const identifier = (channel: string): string => {
  const s = channel.replace(/[^A-Za-z0-9_$]/g, '_');
  return /^[0-9]/.test(s) ? `_${s}` : s;
};

/** Render the optional TypeScript companion module. */
export function renderTsModule(m: ArtManifest): string {
  const lines = [
    '/**',
    ' * GENERATED by art-commission wire — do not edit by hand.',
    ` * ${m.counts.wired} of ${m.counts.catalogued} catalogued assets have art on disk.`,
    ' * Look keys up per channel; a missing key means: use the code-drawn fallback.',
    ' */',
    '',
  ];
  for (const [channel, entries] of Object.entries(m.channels)) {
    lines.push(`export const ${identifier(channel)}: Record<string, string> = {`);
    for (const [key, out] of Object.entries(entries)) {
      lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(out)},`);
    }
    lines.push('};', '');
  }
  // Keep the file a valid ES module even when nothing is on disk yet (0 channels),
  // so a namespace import (`import * as m from './artManifest'`) still type-checks.
  if (Object.keys(m.channels).length === 0) lines.push('export {};', '');
  return lines.join('\n');
}

export async function writeManifest(c: ResolvedCommission, opts: { ts?: boolean } = {}): Promise<WireScan> {
  const scan = buildManifest(c);
  await mkdir(dirname(c.manifestPath), { recursive: true });
  await writeFile(c.manifestPath, JSON.stringify(scan.manifest, null, 2) + '\n');
  if (opts.ts) {
    const tsPath = c.manifestPath.replace(/\.json$/, '') + '.ts';
    await writeFile(tsPath, renderTsModule(scan.manifest));
  }
  return scan;
}

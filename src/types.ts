/**
 * The commission-file format — the standard, engine-agnostic data contract for
 * commissioning AI-generated game art.
 *
 * A game exports ONE file (JSON, or a JS module default-exporting the same
 * shape) describing every asset it wants procured: what to draw (prompt), how
 * to treat the pixels afterwards (kind/post), where the file lands (out), and
 * how the game will look it up (channel/key). The CLI consumes this file for
 * everything — cost planning, generation, reprocessing, and manifest emission.
 *
 * Design rules carried over from the pipeline this generalizes:
 *   - Generation is resumable and spend-safe: files on disk are skipped,
 *     every raw original is kept, and post-processing is re-runnable for free.
 *   - Image models cannot emit PNG alpha — transparency is a *contract*:
 *     the prompt demands one exact chroma-key backdrop and local post cuts it.
 *   - Every generated asset should have a code-drawn fallback in the game;
 *     the emitted manifest is guarded (missing file = absent key = fallback).
 */

// ---------------------------------------------------------------- post specs

/** How pixels are treated after the model returns them. */
export interface PostSpec {
  /** Chroma-key the prompted backdrop into real PNG alpha (+ de-spill). */
  cutout: boolean;
  /** Trim fully-transparent margins (only meaningful after a cutout). */
  trim: boolean;
  /**
   * How the image meets the target px:
   *   contain — scale to fit INSIDE target px, never cropping, pad transparent
   *   inside  — as contain, but WITHOUT the padding: the stored PNG's own
   *             dimensions are the artwork's, so px is a resolution budget and
   *             not a frame. For consumers that position by the ART (rig parts)
   *             rather than by the frame — see fitInside in post.ts.
   *   cover   — scale to fill target px exactly (same-aspect sources)
   *   none    — keep the model's native resolution untouched
   */
  fit: 'contain' | 'cover' | 'inside' | 'none';
  /** Hard-lock every opaque pixel to the nearest palette colour. */
  quantize: boolean;
  /**
   * Resampling kernel for fits. 'nearest' preserves pixel-art crispness;
   * 'lanczos3' suits painterly/HD art.
   */
  kernel: 'nearest' | 'lanczos3';
}

/**
 * Built-in kinds — shorthand bundles of PostSpec + sizing behaviour. A kind is
 * just a named preset; per-asset `post` overrides win, and commission files
 * can define additional kinds (or reconfigure these) under `kinds`.
 *
 *   cutout — an isolated object on the chroma key → alpha sprite fit inside
 *            target px × pxScale (props, icons, weapon plates, decals…)
 *   plate  — a full-bleed scene resized to exact target px (room plates,
 *            floor centrepieces, backgrounds)
 *   tile   — a seamless full-bleed texture at exact target px, palette-locked
 *            when a palette is configured (tiling floors/terrain)
 *   still  — full-frame key art kept at the model's native resolution
 *            (cutscene/story backdrops the engine scales itself)
 */
export type BuiltinKind = 'cutout' | 'plate' | 'tile' | 'still';

/** A kind definition: post treatment + generation-side defaults. */
export interface KindSpec extends PostSpec {
  /**
   * Whether `pxScale` multiplies the stored size. True for contain-fit sprites
   * (stored detail headroom is free — display is size-driven); false for
   * surfaces baked at exact game px, where extra resamples read as mud.
   */
  scaled: boolean;
  /** Append the auto-built chroma-key clause to prompts of this kind. */
  keyClause: boolean;
}

// -------------------------------------------------------------------- assets

/** A derived companion generated by EDITING the fresh base image (same
 *  silhouette/palette carried by the reference): broken/debris states, wear
 *  tiers, damage variants, recolours. */
export interface DerivedSpec {
  /** Unique id (also the default manifest key). */
  id: string;
  /** The edit instruction; the parent's generated image is attached as the
   *  reference. The chroma-key clause is appended when the post cuts out. */
  prompt: string;
  /** Output path relative to `paths.assetRoot`. */
  out: string;
  /** Target px; defaults to the parent's. */
  px?: [number, number];
  /** Manifest channel; defaults to the parent's. */
  channel?: string;
  /** Manifest key within the channel; defaults to `id`. */
  key?: string;
  /** Post overrides; defaults to the parent's resolved post. */
  post?: Partial<PostSpec>;
}

/** One commissionable asset. */
export interface AssetSpec {
  /** Unique id across the file. */
  id: string;
  /** Kind preset (built-in or defined under `kinds`). Default 'cutout'. */
  kind?: string;
  /**
   * The subject/scene text. The tool wraps it: `style.prefix` + prompt +
   * key clause (cutout kinds) + `style.suffix` + negatives. Write the subject
   * here, keep the shared look in `style`.
   */
  prompt: string;
  /** Extra negative clauses for this asset (after `style.negative`). */
  negative?: string;
  /** Final target size in game px `[w, h]`. Required unless fit is 'none'. */
  px?: [number, number];
  /** Output path relative to `paths.assetRoot` (e.g. "skins/castle/urn.png"). */
  out: string;
  /** Manifest channel — one exported map per channel (e.g. "FLOOR_ART").
   *  Default "art". */
  channel?: string;
  /** Manifest key within the channel. Default `id`. */
  key?: string;
  /** Free-form grouping (biome, sequence, category…) — filterable, and the
   *  fallback directory probed by `--ref-dir`. */
  group?: string;
  /** Free-form labels — filterable via `--tag`. */
  tags?: string[];
  /** Higher = generated sooner under `--top`. Default 0. */
  priority?: number;
  /** false = catalogued but neither generated (without --include-disabled)
   *  nor wired. Default true. */
  enabled?: boolean;
  /**
   * img2img composition anchor: a path (relative to the commission file) to an
   * image the model should redraw — e.g. the game's own procedural render.
   * Carries composition + palette; `style.refSuffix` is appended to the prompt.
   */
  ref?: string;
  /**
   * Style anchor: the `id` of ANOTHER asset in this file whose generated
   * output is fed back as a style reference. Anchors are generated first;
   * `style.anchorSuffix` is appended to this asset's prompt. This is how a
   * sequence holds one look without one plate's palette bleeding into all.
   */
  styleAnchor?: string;
  /** Aspect-ratio hint override, e.g. "16:9" (default: derived from px). */
  aspect?: string;
  /** Deterministic seed, for providers that honour one. */
  seed?: number;
  /** Per-asset model override. */
  model?: string;
  /** Per-asset provider override. */
  provider?: string;
  /** Opaque provider-specific parameters (e.g. Retro Diffusion prompt_style). */
  providerOptions?: Record<string, unknown>;
  /** Post overrides on top of the kind preset. */
  post?: Partial<PostSpec>;
  /** Derived companions edited from the fresh base. */
  derive?: DerivedSpec[];
}

// ----------------------------------------------------------------- file root

export interface StyleSpec {
  /** Prepended to every prompt (a global STYLE block). */
  prefix?: string;
  /** Appended after the subject + key clause (palette/lighting/mood blocks). */
  suffix?: string;
  /** Global negative clauses, appended last (providers with a separate
   *  negative-prompt field receive them there instead). */
  negative?: string;
  /** Appended when an img2img `ref` image is attached. */
  refSuffix?: string;
  /** Appended when a `styleAnchor` output is attached. */
  anchorSuffix?: string;
}

export interface PathsSpec {
  /** Root for asset `out` paths, relative to the commission file. Default ".". */
  assetRoot?: string;
  /** Where untouched model originals are kept (mirror of `out`), relative to
   *  the commission file. Default ".art-raw". */
  rawRoot?: string;
  /** Manifest path written by `wire`, relative to the commission file.
   *  Default "art-manifest.json". */
  manifest?: string;
}

export interface ProviderConfig {
  /** Model id default for this provider. */
  model?: string;
  /** Environment variable(s) holding the API key, first hit wins. */
  apiKeyEnv?: string | string[];
  /** API base URL override. */
  baseUrl?: string;
  /** Provider-specific size hint (e.g. Gemini imageSize "1K"/"2K"). */
  imageSize?: string;
  /** Rough per-image USD for cost previews: overrides built-in guesses. */
  costPerImage?: { sync?: number; batch?: number };
  /** Extra provider-specific defaults merged under each request's options. */
  options?: Record<string, unknown>;
}

export interface CommissionFile {
  /** Format version. Currently 1. */
  version: 1;
  /** Display name for logs. */
  name?: string;
  /** Optional JSON-schema pointer for editors ($schema is ignored). */
  $schema?: string;
  paths?: PathsSpec;
  style?: StyleSpec;
  /** Palette hexes ("#rrggbb") — enables `quantize` posts. */
  palette?: string[];
  /** Chroma-key backdrop colour for cutouts. Default "#ff00ff". */
  chromaKey?: string;
  /** Squared-distance tolerance for the key clear. Default 110. */
  chromaTolerance?: number;
  /** Stored-size multiplier for scaled kinds (detail headroom). Default 1. */
  pxScale?: number;
  providers?: {
    /** Which provider `generate` uses by default. Default "gemini". */
    default?: string;
  } & Record<string, ProviderConfig | string | undefined>;
  /** Additional kind presets, or overrides of the built-ins. */
  kinds?: Record<string, Partial<KindSpec>>;
  assets: AssetSpec[];
}

// -------------------------------------------------------------- resolved row

/** An asset with every default folded in — what the pipeline consumes. */
export interface ResolvedAsset {
  id: string;
  kind: string;
  prompt: string;
  negative?: string;
  px?: [number, number];
  /** Stored px after pxScale ([w,h]); undefined when fit is 'none'. */
  storePx?: [number, number];
  out: string;
  /** Absolute output path. */
  outAbs: string;
  /** Absolute raw-original path. */
  rawAbs: string;
  channel: string;
  key: string;
  group?: string;
  tags: string[];
  priority: number;
  enabled: boolean;
  ref?: string;
  refAbs?: string;
  styleAnchor?: string;
  aspect?: string;
  seed?: number;
  model?: string;
  provider?: string;
  providerOptions?: Record<string, unknown>;
  post: PostSpec;
  scaled: boolean;
  derive: ResolvedDerived[];
}

export interface ResolvedDerived {
  id: string;
  prompt: string;
  out: string;
  outAbs: string;
  rawAbs: string;
  px?: [number, number];
  storePx?: [number, number];
  channel: string;
  key: string;
  post: PostSpec;
}

/** The whole commission, resolved against its file location. */
export interface ResolvedCommission {
  file: string;
  /** Directory of the commission file — every relative path resolves here. */
  baseDir: string;
  name: string;
  assetRoot: string;
  rawRoot: string;
  manifestPath: string;
  style: Required<Pick<StyleSpec, 'refSuffix' | 'anchorSuffix'>> & StyleSpec;
  palette: string[];
  chromaKey: string;
  chromaKeyRgb: [number, number, number];
  chromaTolerance: number;
  pxScale: number;
  defaultProvider: string;
  providers: Record<string, ProviderConfig>;
  kinds: Record<string, KindSpec>;
  assets: ResolvedAsset[];
}
